package org.firstinspires.ftc.teamcode.util;

public class ShotValues {
    public double turretAngle, turretVelocity, hoodAngle, rpm;

    public ShotValues(double rpm, double hoodAngle, double turretAngle, double turretVelocity) {
        this.turretAngle = turretAngle;
        this.turretVelocity = turretVelocity;
        this.hoodAngle = hoodAngle;
        this.rpm = rpm;
    }
}
